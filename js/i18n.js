const I18N_STORAGE_KEY = 'bkm_idioma';

/** Idioma activo actualmente ('es' | 'en'). */
function getIdioma() {
    return localStorage.getItem(I18N_STORAGE_KEY) || 'es';
}

/** Traduce una clave al idioma activo. Cae a español y luego a la clave misma. */
function t(key) {
    if (!key) return '';
    const lang = getIdioma();
    return (I18N_DICT[lang] && I18N_DICT[lang][key])
        || (I18N_DICT.es && I18N_DICT.es[key])
        || key;
}

/** Aplica las traducciones a todos los elementos marcados con data-i18n* dentro de `root`. */
function aplicarIdioma(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => {
        el.innerHTML = t(el.dataset.i18nHtml);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.setAttribute('title', t(el.dataset.i18nTitle));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => {
        el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });
    document.documentElement.setAttribute('lang', getIdioma());
}

/**
 * Cambia el idioma activo: lo persiste en localStorage, re-renderiza el DOM
 * (incluido el sidebar, que se reconstruye porque sus textos se generan en JS)
 * y sincroniza la preferencia con el backend si hay sesión activa.
 */
function cambiarIdioma(lang) {
    if (lang !== 'es' && lang !== 'en') return;
    localStorage.setItem(I18N_STORAGE_KEY, lang);

    /* El sidebar arma sus textos en JS (sidebar.js) — hay que reconstruirlo
       para que tome el nuevo idioma, no solo re-aplicar data-i18n. */
    const menuUl = document.getElementById('sidebarMenu');
    if (menuUl && typeof window.reconstruirSidebar === 'function') {
        window.reconstruirSidebar();
    }

    aplicarIdioma(document);

    /* Sincronizar con el backend (silencioso — no bloquea el cambio visual) */
    if (typeof apiFetch === 'function' && localStorage.getItem('authToken')) {
        apiFetch('/usuarios/configuracion', {
            method: 'PUT',
            body: JSON.stringify({ idioma: lang })
        }).catch(() => { /* si falla, el idioma igual quedó aplicado localmente */ });
    }

    /* Reflejar el cambio en el <select> de Configuración si está en esta página */
    const selConfig = document.getElementById('config-idioma');
    if (selConfig) selConfig.value = lang;

    document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
        btn.textContent = lang === 'es' ? 'EN' : 'ES';
        btn.title = lang === 'es' ? 'Switch to English' : 'Cambiar a Español';
    });
}

/**
 * Inserta un botón compacto de cambio de idioma en la barra superior
 * (`.header-right`, junto al botón de tema/campana) si existe en la página.
 * Si no hay header interno (páginas públicas: login/registro/index), lo
 * agrega como un botón flotante en la esquina superior derecha.
 */
function initLanguageToggle() {
    if (document.querySelector('[data-lang-toggle]')) return; // ya existe

    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'btn-icon';
    btn.setAttribute('data-lang-toggle', '');
    btn.setAttribute('aria-label', 'Cambiar idioma / Switch language');
    const lang = getIdioma();
    btn.textContent = lang === 'es' ? 'EN' : 'ES';
    btn.title = lang === 'es' ? 'Switch to English' : 'Cambiar a Español';
    btn.addEventListener('click', () => cambiarIdioma(getIdioma() === 'es' ? 'en' : 'es'));

    const headerRight = document.querySelector('.header-right');
    if (headerRight) {
        headerRight.insertBefore(btn, headerRight.firstChild);
        return;
    }

    /* Páginas públicas sin topbar interno: botón flotante */
    btn.style.cssText = 'position:fixed;top:16px;right:16px;z-index:9999;' +
        'background:#fff;border:1px solid #e2e8f0;border-radius:8px;' +
        'padding:.4rem .7rem;font-size:.8rem;font-weight:700;color:#005F73;cursor:pointer;' +
        'box-shadow:0 2px 8px rgba(0,0,0,.08);';
    document.body.appendChild(btn);
}

document.addEventListener('DOMContentLoaded', () => {
    aplicarIdioma(document);
    initLanguageToggle();
});